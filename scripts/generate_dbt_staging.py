"""Generate dbt sources, staging models and their schema tests from the data contracts.

Staging models are intentionally mechanical (dedupe, typing, code standardisation, lineage), so they
are generated from ``finance_common/contracts.py`` to guarantee they never drift from the contracts.
Business logic lives in intermediate/core/mart models, which are hand-written.

    python scripts/generate_dbt_staging.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import yaml  # noqa: E402

from finance_common import contracts  # noqa: E402

STAGING = ROOT / "dbt_finance" / "models" / "staging"
SYSTEM_ALIAS = {"erp": "erp", "crm": "crm", "banking": "bank", "payroll": "payroll", "budgeting": "budget", "fx": "fx"}
MODEL_NAME_OVERRIDES = {
    ("banking", "bank_transactions"): "stg_bank__transactions",
    ("banking", "account_balances"): "stg_bank__balances",
    ("payroll", "payroll_transactions"): "stg_payroll__transactions",
    ("payroll", "employee_job_history"): "stg_payroll__job_history",
    ("budgeting", "budget_plans"): "stg_budget__plans",
}
CODE_COLUMNS = {
    "currency",
    "transaction_currency",
    "functional_currency",
    "reporting_currency",
    "source_currency",
    "target_currency",
    "salary_currency",
    "billing_currency",
    "country",
}
STATUS_SUFFIXES = (
    "_status",
    "_type",
    "_direction",
    "_method",
    "_category",
    "normal_balance",
    "segment",
    "scenario",
    "budget_version",
    "stage",
    "rate_type",
)
FRESHNESS = {
    "erp": (26, 50),
    "crm": (26, 50),
    "banking": (50, 98),
    "payroll": (24 * 35, 24 * 45),
    "budgeting": (24 * 120, 24 * 200),
    "fx": (50, 98),
}
HEADER = (
    "-- GENERATED by scripts/generate_dbt_staging.py from finance_common/contracts.py.\n"
    "-- Do not edit by hand: change the data contract and regenerate.\n"
)


def model_name(t: contracts.TableContract) -> str:
    return MODEL_NAME_OVERRIDES.get((t.system, t.name), f"stg_{SYSTEM_ALIAS[t.system]}__{t.name}")


def column_expr(c: contracts.Column) -> str:
    q = f'"{c.name}"'
    if c.type == "money":
        expr = f"{{{{ to_money('{q}') }}}}"
    elif c.type == "rate":
        expr = f"{{{{ to_rate('{q}') }}}}"
    elif c.type in ("qty", "pct"):
        expr = f"cast({q} as decimal(18, 4))"
    elif c.type == "ts":
        expr = f"{{{{ to_utc('{q}') }}}}"
    elif c.type == "str" and (c.name in CODE_COLUMNS or c.name.endswith(STATUS_SUFFIXES)):
        expr = f"{{{{ clean_code('{q}') }}}}"
    elif c.type == "str":
        expr = f"nullif(trim({q}), '')"
    else:
        expr = q
    return f"{expr} as {c.name}"


def render_model(t: contracts.TableContract) -> str:
    vis = "updated_at" if "updated_at" in t.column_names else "publication_timestamp"
    keys = ", ".join(f"'{k}'" for k in t.primary_key)
    cols = ",\n        ".join(column_expr(c) for c in t.columns)
    where = ""
    if t.fqn == "fx.exchange_rates":
        where = (
            "\n    -- invalid publications (non-positive rates) are excluded here and surfaced by\n"
            "    -- int_fx_rate_quarantine; they are never used for conversion\n    where exchange_rate > 0"
        )
    return f"""{HEADER}
with source as (
    select * from {{{{ source('{t.system}', '{t.name}') }}}}
),

deduplicated as (
    {{{{ dedupe_latest('source', [{keys}], '{vis}') }}}}
)

select
        {cols},
        {{{{ ingestion_lineage() }}}}
from deduplicated{where}
"""


def main() -> None:
    STAGING.mkdir(parents=True, exist_ok=True)
    by_system: dict[str, list[contracts.TableContract]] = {}
    for t in contracts.TABLES.values():
        by_system.setdefault(t.system, []).append(t)
    for system, tables in by_system.items():
        folder = STAGING / SYSTEM_ALIAS[system]
        folder.mkdir(exist_ok=True)
        warn, err = FRESHNESS[system]
        sources = {
            "version": 2,
            "sources": [
                {
                    "name": system,
                    "schema": "finance_raw",
                    "description": f"Raw, append-only extracts of the {system.upper()} source system (one row per record version).",
                    "loaded_at_field": "_loaded_at",
                    "freshness": {
                        "warn_after": {"count": warn, "period": "hour"},
                        "error_after": {"count": err, "period": "hour"},
                    },
                    "tables": [
                        {
                            "name": t.name,
                            "identifier": f"{system}__{t.name}",
                            "description": t.description,
                            "meta": {"owner": t.owner, "delivery": t.delivery, "primary_key": list(t.primary_key)},
                        }
                        for t in tables
                    ],
                }
            ],
        }
        (folder / f"_{SYSTEM_ALIAS[system]}__sources.yml").write_text(
            "# GENERATED by scripts/generate_dbt_staging.py\n" + yaml.safe_dump(sources, sort_keys=False),
            encoding="utf-8",
        )
        models = []
        for t in tables:
            name = model_name(t)
            (folder / f"{name}.sql").write_text(render_model(t), encoding="utf-8")
            cols = []
            for c in t.columns:
                col: dict = {"name": c.name, "description": c.description or c.name.replace("_", " ")}
                tests: list = []
                if len(t.primary_key) == 1 and c.name == t.primary_key[0]:
                    tests += ["unique", "not_null"]
                elif not c.nullable and c.name in t.primary_key:
                    tests.append("not_null")
                if c.name in CODE_COLUMNS and c.name != "country":
                    tests.append(
                        {
                            "accepted_values": {
                                "arguments": {
                                    "values": sorted(
                                        ["EUR", "GBP", "USD", "CAD", "JPY", "SGD", "INR", "CHF", "SEK", "CNY"]
                                    )
                                }
                            }
                        }
                    )
                if c.sensitive:
                    col["meta"] = {"sensitivity": c.sensitive}
                    col.setdefault("tags", []).append(f"pii:{c.sensitive.lower()}")
                if tests:
                    col["data_tests"] = tests
                cols.append(col)
            model = {
                "name": name,
                "description": f"{t.description} Latest version per primary key.",
                "meta": {"owner": t.owner, "source_contract": t.fqn, "grain": " x ".join(t.primary_key)},
                "columns": cols,
            }
            if len(t.primary_key) > 1:
                model["data_tests"] = [
                    {"unique_combination_of_columns": {"arguments": {"columns": list(t.primary_key)}}}
                ]
            models.append(model)
        (folder / f"_{SYSTEM_ALIAS[system]}__models.yml").write_text(
            "# GENERATED by scripts/generate_dbt_staging.py\n"
            + yaml.safe_dump({"version": 2, "models": models}, sort_keys=False, width=110),
            encoding="utf-8",
        )
    print(f"generated staging for {len(contracts.TABLES)} contracts")


if __name__ == "__main__":
    main()
